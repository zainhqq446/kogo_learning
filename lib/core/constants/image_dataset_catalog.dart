/// Representasi entri gambar dalam dataset resmi pembelajaran Kogo Voice Learning.
class ImageDatasetEntry {
  final String word;
  final String stageFolder;
  final String category;
  final String assetPath;

  const ImageDatasetEntry({
    required this.word,
    required this.stageFolder,
    required this.category,
    required this.assetPath,
  });

  /// Mengembalikan nomor stage berdasarkan folder:
  /// 1: Dua suku kata
  /// 2: Tiga suku kata
  /// 3: Lebih dari tiga suku kata
  int get stageNumber {
    if (stageFolder.startsWith('1_')) return 2; // Sesuai kurikulum DB: Stage 2 adalah Dua Suku Kata
    if (stageFolder.startsWith('2_')) return 3; // Stage 3 adalah Tiga Suku Kata
    if (stageFolder.startsWith('3_')) return 4; // Stage 4 adalah Banyak Suku Kata
    return 1;
  }
}

